from typing import Protocol

from app.domain import Message, Order, OrderStatus, OutboxEvent


class Repository(Protocol):
    async def create_with_outbox(self, order: Order, event: OutboxEvent) -> None: ...
    async def get_order(self, order_id: str) -> Order | None: ...
    async def get_by_idempotency_key(self, key: str) -> Order | None: ...
    async def set_status(self, order_id: str, status: OrderStatus) -> None: ...
    async def fetch_unpublished(self, limit: int) -> list[OutboxEvent]: ...
    async def mark_published(self, event_ids: list[str]) -> None: ...


class KeyStore(Protocol):
    async def set_if_absent(self, key: str, ttl_seconds: int) -> bool: ...
    async def delete(self, key: str) -> None: ...


class EventPublisher(Protocol):
    async def publish(self, event: OutboxEvent) -> None: ...


class RetryBus(Protocol):
    async def send_retry(self, msg: Message, delay_ms: int) -> None: ...
    async def send_dlq(self, msg: Message, reason: str) -> None: ...
